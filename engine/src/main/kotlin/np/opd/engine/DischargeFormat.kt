package np.opd.engine

/**
 * Discharge summary formatting. Pure: given a structured [DischargeInput] it produces a clean
 * plain-text export (safe to paste into a terminal-based hospital EMR — no tables, no markdown
 * escapes, no orphaned characters) and a markdown variant for printing.
 *
 * Two shapes share one renderer: an ER attendance (fast triage, short course) and an inpatient
 * admission (multi-day course, operative detail, home regimen). Fields irrelevant to the shape are
 * simply omitted, so the same formatter serves both.
 *
 * The AI never writes this text; every line comes from the doctor's entries and fixed labels.
 */
object DischargeFormat {

    enum class Kind { ER, INPATIENT }

    /** One take-home medicine line. Instructions come from templates or the doctor's own words. */
    data class DischargeMed(
        val name: String,
        val dose: String = "",
        val route: String = "",
        val frequency: String = "",
        val durationDays: Int? = null,
        val instructionEn: String = "",
        val instructionNe: String = "",
        /** true when this is a chronic medicine being resumed rather than a new course. */
        val continued: Boolean = false
    )

    data class DischargeInput(
        val kind: Kind = Kind.INPATIENT,
        // Header
        val patientName: String = "",
        val age: Int? = null,
        val sex: String = "",
        val mrn: String? = null,
        val ward: String = "",
        val bed: String = "",
        val unit: String = "",
        val consultant: String = "",
        val admissionDate: String = "",
        val dischargeDate: String = "",
        // Surgical (inpatient)
        val procedureName: String? = null,
        val preoperativeDiagnosis: String? = null,
        val postoperativeDiagnosis: String? = null,
        val operativeFindings: String? = null,
        // Narrative (both; ER uses "presentingComplaints" as the complaint + interventions in course)
        val presentingComplaints: String = "",
        val hospitalCourse: String = "",
        // Disposition
        val dischargeVitals: String = "",
        val homeMedications: List<DischargeMed> = emptyList(),
        val woundNursingAdvice: String = "",
        val redFlagsReturn: String = "",
        val followUp: String = "",
        // Governance footer
        val prototypeNotice: String = "PROTOTYPE - TEST DATA ONLY - NOT A VALID DISCHARGE SUMMARY"
    )

    private const val RULE = "======================================================================"
    private const val THIN_RULE = "----------------------------------------------------------------------"

    /** Clean plain text for copy/paste into a PC EMR or terminal-based system. */
    fun plainText(d: DischargeInput): String {
        val sb = StringBuilder()
        val heading = if (d.kind == Kind.ER) "EMERGENCY DEPARTMENT DISCHARGE SUMMARY" else "INPATIENT DISCHARGE SUMMARY"
        sb.appendLine(RULE)
        sb.appendLine(centred(heading))
        sb.appendLine(RULE)
        sb.appendLine("!! ${d.prototypeNotice}")
        sb.appendLine()
        appendHeader(sb, d)

        when (d.kind) {
            Kind.ER -> appendEr(sb, d)
            Kind.INPATIENT -> appendInpatient(sb, d)
        }

        appendDisposition(sb, d)

        sb.appendLine(RULE)
        sb.appendLine("Generated by OPD Assistant prototype. Clinical content is UNVERIFIED.")
        return sb.toString()
    }

    /** Markdown variant for formatted printing. */
    fun markdown(d: DischargeInput): String {
        val sb = StringBuilder()
        val heading = if (d.kind == Kind.ER) "Emergency Department Discharge Summary" else "Inpatient Discharge Summary"
        sb.appendLine("# $heading")
        sb.appendLine()
        sb.appendLine("> **${d.prototypeNotice}**")
        sb.appendLine()
        appendHeaderMd(sb, d)
        when (d.kind) {
            Kind.ER -> appendErMd(sb, d)
            Kind.INPATIENT -> appendInpatientMd(sb, d)
        }
        appendDispositionMd(sb, d)
        sb.appendLine()
        sb.appendLine("_Generated by OPD Assistant prototype. Clinical content is UNVERIFIED._")
        return sb.toString()
    }

    /* ------------------------------- plain text ------------------------------- */

    private fun appendHeader(sb: StringBuilder, d: DischargeInput) {
        sb.appendLine("Patient    : ${blank(d.patientName)}")
        val demo = listOfNotNull(
            d.age?.let { "$it years" },
            d.sex.takeIf { it.isNotBlank() }
        ).joinToString(", ")
        if (demo.isNotBlank()) sb.appendLine("Age / Sex  : $demo")
        d.mrn?.takeIf { it.isNotBlank() }?.let { sb.appendLine("MRN        : $it") }
        val location = listOfNotNull(
            d.ward.takeIf { it.isNotBlank() },
            d.bed.takeIf { it.isNotBlank() }?.let { "Bed $it" },
            d.unit.takeIf { it.isNotBlank() }
        ).joinToString(" / ")
        if (location.isNotBlank()) sb.appendLine("Location   : $location")
        if (d.consultant.isNotBlank()) sb.appendLine("Consultant : ${d.consultant}")
        sb.appendLine("Admission  : ${blank(d.admissionDate)}")
        sb.appendLine("Discharge  : ${blank(d.dischargeDate)}")
        sb.appendLine(THIN_RULE)
    }

    private fun appendEr(sb: StringBuilder, d: DischargeInput) {
        section(sb, "PRESENTING COMPLAINT", d.presentingComplaints)
        section(sb, "ER COURSE / INTERVENTIONS", d.hospitalCourse)
    }

    private fun appendInpatient(sb: StringBuilder, d: DischargeInput) {
        d.preoperativeDiagnosis?.takeIf { it.isNotBlank() }?.let { section(sb, "PRE-OPERATIVE DIAGNOSIS", it) }
        d.postoperativeDiagnosis?.takeIf { it.isNotBlank() }?.let { section(sb, "POST-OPERATIVE DIAGNOSIS", it) }
        d.procedureName?.takeIf { it.isNotBlank() }?.let { section(sb, "PROCEDURE", it) }
        d.operativeFindings?.takeIf { it.isNotBlank() }?.let { section(sb, "OPERATIVE FINDINGS", it) }
        section(sb, "PRESENTING COMPLAINT", d.presentingComplaints)
        section(sb, "HOSPITAL COURSE", d.hospitalCourse)
    }

    private fun appendDisposition(sb: StringBuilder, d: DischargeInput) {
        if (d.dischargeVitals.isNotBlank()) section(sb, "DISCHARGE VITALS", d.dischargeVitals)
        sb.appendLine("MEDICATIONS ON DISCHARGE")
        if (d.homeMedications.isEmpty()) {
            sb.appendLine("  (none recorded)")
        } else {
            d.homeMedications.forEachIndexed { i, m ->
                sb.appendLine("  ${i + 1}. ${medLine(m)}")
                val instr = listOfNotNull(m.instructionEn.takeIf { it.isNotBlank() }, m.instructionNe.takeIf { it.isNotBlank() })
                    .joinToString(" | ")
                if (instr.isNotBlank()) sb.appendLine("     $instr")
            }
        }
        sb.appendLine()
        if (d.woundNursingAdvice.isNotBlank()) section(sb, "WOUND & NURSING ADVICE", d.woundNursingAdvice)
        section(sb, "RETURN TO HOSPITAL IF", d.redFlagsReturn)
        section(sb, "FOLLOW-UP", d.followUp)
    }

    private fun medLine(m: DischargeMed): String {
        val parts = mutableListOf<String>()
        parts += m.name
        if (m.dose.isNotBlank()) parts += m.dose
        if (m.route.isNotBlank()) parts += m.route
        val header = parts.joinToString(" ")
        val tail = buildList {
            if (m.frequency.isNotBlank()) add(m.frequency)
            m.durationDays?.let { add("x $it days") }
            if (m.continued) add("(continued)")
        }.joinToString(" ")
        return if (tail.isBlank()) header else "$header - $tail"
    }

    private fun section(sb: StringBuilder, title: String, body: String) {
        if (body.isBlank()) return
        sb.appendLine(title)
        body.trim().split('\n').forEach { line -> sb.appendLine("  ${line.trim()}") }
        sb.appendLine()
    }

    /* ------------------------------- markdown ------------------------------- */

    private fun appendHeaderMd(sb: StringBuilder, d: DischargeInput) {
        sb.appendLine("- **Patient:** ${blank(d.patientName)}")
        val demo = listOfNotNull(d.age?.let { "$it years" }, d.sex.takeIf { it.isNotBlank() }).joinToString(", ")
        if (demo.isNotBlank()) sb.appendLine("- **Age / Sex:** $demo")
        d.mrn?.takeIf { it.isNotBlank() }?.let { sb.appendLine("- **MRN:** $it") }
        val location = listOfNotNull(
            d.ward.takeIf { it.isNotBlank() },
            d.bed.takeIf { it.isNotBlank() }?.let { "Bed $it" },
            d.unit.takeIf { it.isNotBlank() }
        ).joinToString(" / ")
        if (location.isNotBlank()) sb.appendLine("- **Location:** $location")
        if (d.consultant.isNotBlank()) sb.appendLine("- **Consultant:** ${d.consultant}")
        sb.appendLine("- **Admission:** ${blank(d.admissionDate)}")
        sb.appendLine("- **Discharge:** ${blank(d.dischargeDate)}")
        sb.appendLine()
    }

    private fun appendErMd(sb: StringBuilder, d: DischargeInput) {
        mdSection(sb, "Presenting complaint", d.presentingComplaints)
        mdSection(sb, "ER course / interventions", d.hospitalCourse)
    }

    private fun appendInpatientMd(sb: StringBuilder, d: DischargeInput) {
        d.preoperativeDiagnosis?.takeIf { it.isNotBlank() }?.let { mdSection(sb, "Pre-operative diagnosis", it) }
        d.postoperativeDiagnosis?.takeIf { it.isNotBlank() }?.let { mdSection(sb, "Post-operative diagnosis", it) }
        d.procedureName?.takeIf { it.isNotBlank() }?.let { mdSection(sb, "Procedure", it) }
        d.operativeFindings?.takeIf { it.isNotBlank() }?.let { mdSection(sb, "Operative findings", it) }
        mdSection(sb, "Presenting complaint", d.presentingComplaints)
        mdSection(sb, "Hospital course", d.hospitalCourse)
    }

    private fun appendDispositionMd(sb: StringBuilder, d: DischargeInput) {
        if (d.dischargeVitals.isNotBlank()) mdSection(sb, "Discharge vitals", d.dischargeVitals)
        sb.appendLine("## Medications on discharge")
        sb.appendLine()
        if (d.homeMedications.isEmpty()) {
            sb.appendLine("_None recorded._")
        } else {
            d.homeMedications.forEachIndexed { i, m ->
                sb.appendLine("- **${medLine(m)}**")
                val instr = listOfNotNull(m.instructionEn.takeIf { it.isNotBlank() }, m.instructionNe.takeIf { it.isNotBlank() })
                    .joinToString(" | ")
                if (instr.isNotBlank()) sb.appendLine("  - $instr")
            }
        }
        sb.appendLine()
        mdSection(sb, "Wound & nursing advice", d.woundNursingAdvice)
        mdSection(sb, "Return to hospital if", d.redFlagsReturn)
        mdSection(sb, "Follow-up", d.followUp)
    }

    private fun mdSection(sb: StringBuilder, title: String, body: String) {
        if (body.isBlank()) return
        sb.appendLine("## $title")
        sb.appendLine()
        sb.appendLine(body.trim())
        sb.appendLine()
    }

    /* ------------------------------- helpers ------------------------------- */

    private fun blank(s: String): String = if (s.isBlank()) "—" else s

    private fun centred(s: String, width: Int = RULE.length): String {
        if (s.length >= width) return s
        val pad = (width - s.length) / 2
        return " ".repeat(pad) + s
    }
}
