package np.opd.engine

/**
 * Operative note engine. Pure structure + rendering: builds a surgeon's operative note into clean
 * copy-paste text and markdown, and turns a free-text list of immediate post-op orders into
 * candidate drug lines that have been through the deterministic [Safety] engine.
 *
 * The AI never writes the note or chooses drugs; the doctor dictates/fills the fields and the
 * engine formats and safety-checks them.
 */
object OpNoteFormat {

    data class Data(
        val procedureTitle: String,
        val preOpDiagnosis: String,
        val postOpDiagnosis: String,
        val surgeonName: String,
        val assistantName: String? = null,
        val anesthetistName: String? = null,
        val anesthesiaType: String = "GA",
        val incision: String,
        val operativeFindings: String,
        val procedureSteps: String,
        val bloodLossMl: Int? = null,
        val drains: String? = null,
        val specimenSent: String? = null,
        val spongeCountCorrect: Boolean = true,
        val immediatePostOpOrders: List<String> = emptyList()
    )

    /** A post-op order line parsed into a candidate cardex item, with its safety findings. */
    data class CandidateOrder(
        val stated: String,
        val drugId: String?,
        val drugName: String,
        val route: String?,
        val doseCount: Double?,
        val frequency: String?,
        val findings: List<SafetyFinding> = emptyList()
    ) {
        val blocked: Boolean get() = findings.any { it.severity == Severity.BLOCKED }
        val inFormulary: Boolean get() = drugId != null
    }

    private const val RULE = "======================================================================"
    private const val THIN = "----------------------------------------------------------------------"

    fun cleanText(d: Data): String {
        val sb = StringBuilder()
        sb.appendLine(RULE)
        sb.appendLine("OPERATIVE NOTE")
        sb.appendLine(RULE)
        sb.appendLine("PROTOTYPE - TEST DATA ONLY - NOT A VALID MEDICAL RECORD")
        sb.appendLine()
        sb.appendLine("Procedure      : ${blank(d.procedureTitle)}")
        sb.appendLine("Surgeon        : ${blank(d.surgeonName)}")
        d.assistantName?.takeIf { it.isNotBlank() }?.let { sb.appendLine("Assistant      : $it") }
        d.anesthetistName?.takeIf { it.isNotBlank() }?.let { sb.appendLine("Anesthetist    : $it") }
        sb.appendLine("Anesthesia     : ${d.anesthesiaType.ifBlank { "—" }}")
        sb.appendLine("Pre-op Dx      : ${blank(d.preOpDiagnosis)}")
        sb.appendLine("Post-op Dx     : ${blank(d.postOpDiagnosis)}")
        sb.appendLine("Incision       : ${blank(d.incision)}")
        d.bloodLossMl?.let { sb.appendLine("Blood loss     : $it mL") }
        d.drains?.takeIf { it.isNotBlank() }?.let { sb.appendLine("Drains         : $it") }
        d.specimenSent?.takeIf { it.isNotBlank() }?.let { sb.appendLine("Specimen sent  : $it") }
        sb.appendLine("Sponge/instr.  : ${if (d.spongeCountCorrect) "count correct" else "DISCREPANCY - recount before closure"}")
        sb.appendLine(THIN)
        section(sb, "OPERATIVE FINDINGS", d.operativeFindings)
        section(sb, "PROCEDURE (STEP BY STEP)", d.procedureSteps)
        if (d.immediatePostOpOrders.isNotEmpty()) {
            sb.appendLine("IMMEDIATE POST-OP ORDERS")
            d.immediatePostOpOrders.forEachIndexed { i, o -> sb.appendLine("  ${i + 1}. $o") }
            sb.appendLine()
        }
        sb.appendLine(RULE)
        sb.appendLine("Generated by OPD Assistant prototype. Clinical content is UNVERIFIED.")
        return sb.toString()
    }

    fun markdown(d: Data): String {
        val sb = StringBuilder()
        sb.appendLine("# Operative Note")
        sb.appendLine()
        sb.appendLine("> PROTOTYPE - TEST DATA ONLY - NOT A VALID MEDICAL RECORD")
        sb.appendLine()
        sb.appendLine("- **Procedure:** ${blank(d.procedureTitle)}")
        sb.appendLine("- **Surgeon:** ${blank(d.surgeonName)}")
        d.assistantName?.takeIf { it.isNotBlank() }?.let { sb.appendLine("- **Assistant:** $it") }
        d.anesthetistName?.takeIf { it.isNotBlank() }?.let { sb.appendLine("- **Anesthetist:** $it") }
        sb.appendLine("- **Anesthesia:** ${d.anesthesiaType.ifBlank { "—" }}")
        sb.appendLine("- **Pre-op Dx:** ${blank(d.preOpDiagnosis)}")
        sb.appendLine("- **Post-op Dx:** ${blank(d.postOpDiagnosis)}")
        sb.appendLine("- **Incision:** ${blank(d.incision)}")
        d.bloodLossMl?.let { sb.appendLine("- **Blood loss:** $it mL") }
        d.drains?.takeIf { it.isNotBlank() }?.let { sb.appendLine("- **Drains:** $it") }
        d.specimenSent?.takeIf { it.isNotBlank() }?.let { sb.appendLine("- **Specimen sent:** $it") }
        sb.appendLine("- **Sponge/instrument count:** ${if (d.spongeCountCorrect) "correct" else "DISCREPANCY"}")
        sb.appendLine()
        mdSection(sb, "Operative findings", d.operativeFindings)
        mdSection(sb, "Procedure (step by step)", d.procedureSteps)
        if (d.immediatePostOpOrders.isNotEmpty()) {
            sb.appendLine("## Immediate post-op orders")
            sb.appendLine()
            d.immediatePostOpOrders.forEach { sb.appendLine("- $it") }
            sb.appendLine()
        }
        sb.appendLine("_Generated by OPD Assistant prototype. Clinical content is UNVERIFIED._")
        return sb.toString()
    }

    /**
     * Parses free-text post-op orders ("Tab Pantop 40mg OD", "IV Ceftriaxone 1g BD",
     * "Inj Tramadol 50mg TDS") into candidate drug uses, matching the formulary and running each
     * through [Safety.evaluate] against the patient context.
     */
    fun extractCandidateOrders(
        orders: List<String>,
        context: CaseState,
        c: Catalogues
    ): List<CandidateOrder> {
        val out = mutableListOf<CandidateOrder>()
        for (raw in orders) {
            val stated = raw.trim()
            if (stated.isBlank()) continue
            if (isNonDrugOrder(stated)) {
                out += CandidateOrder(stated, drugId = null, drugName = stated, route = null, doseCount = null, frequency = null)
                continue
            }
            val drug = c.findDrug(stated)
            val route = detectRoute(stated)
            val dose = detectDose(stated)
            val freq = detectFrequency(stated)
            val findings = if (drug != null) {
                val use = Safety.DrugUse(
                    key = "opnote:${drug.id}",
                    drug = drug,
                    label = drug.generic,
                    unitsPerDose = dose ?: 1.0,
                    dosesPerDay = Safety.dosesPerDay(freq, null)
                )
                Safety.evaluate(listOf(use), Safety.contextUses(context, c), context, c)
            } else {
                listOf(SafetyFinding(Severity.CAUTION, "'$stated' is not in the formulary: safety checks could not run."))
            }
            out += CandidateOrder(
                stated = stated,
                drugId = drug?.id,
                drugName = drug?.generic ?: stated,
                route = route,
                doseCount = dose,
                frequency = freq,
                findings = findings
            )
        }
        return out
    }

    /** IVF, diet, nursing, monitoring lines: recognised but not drug-checked. */
    private fun isNonDrugOrder(s: String): Boolean {
        val t = s.lowercase()
        val nonDrug = listOf("ivf", "iv fluid", "rl", "ns ", "n/s", "dns", "npo", "nil by mouth", "clear fluid", "sips",
            "catheter", "foley", "oxygen", "o2", "monitor", "vitals", "output", "drain", "physio", "diet", "ambulate",
            "position", "inspirometer", "dvt", "compression", "urine", "input", "intake")
        return nonDrug.any { t.contains(it) } && !t.contains("tab ") && !t.contains("cap ") && !t.contains("inj ") && !t.contains("syp ")
    }

    private fun detectRoute(s: String): String? {
        val t = " ${s.lowercase()} "
        return when {
            t.contains(" iv ") || t.startsWith(" iv") || t.contains("intravenous") -> "IV"
            t.contains(" im ") || t.contains("intramuscular") -> "IM"
            t.contains(" sc ") || t.contains("subcut") -> "SC"
            t.contains(" pr ") || t.contains("rectal") -> "PR"
            t.contains(" ng ") || t.contains("ryle") -> "NG"
            t.contains(" tab ") || t.contains(" cap ") || t.contains(" po ") || t.contains("oral") -> "PO"
            t.contains(" inhal") -> "INH"
            else -> null
        }
    }

    private fun detectDose(s: String): Double? {
        // First standalone number followed by a dose unit (mg, g, mcg, ml, iu) or a form.
        val m = Regex("(?i)\\b(\\d+(?:\\.\\d+)?)\\s*(mg|g|mcg|ml|iu|gram|milligram)\\b").find(s)
        return m?.groupValues?.get(1)?.toDoubleOrNull() ?: Regex("\\b(\\d+(?:\\.\\d+)?)\\b").find(s)?.groupValues?.get(1)?.toDoubleOrNull()
    }

    private fun detectFrequency(s: String): String? {
        val t = " ${s.uppercase()} "
        return when {
            Regex("\\bQID\\b|\\bQDS\\b|4 TIMES").containsMatchIn(t) -> "QID"
            Regex("\\bTDS\\b|\\bTID\\b|3 TIMES").containsMatchIn(t) -> "TDS"
            Regex("\\bBD\\b|\\bBID\\b|2 TIMES").containsMatchIn(t) -> "BD"
            Regex("\\bSTAT\\b").containsMatchIn(t) -> "STAT"
            Regex("\\bPRN\\b|SOS").containsMatchIn(t) -> "PRN"
            Regex("\\bHS\\b|BEDTIME|NOCTE").containsMatchIn(t) -> "HS"
            Regex("\\bOD\\b|\\bQD\\b|ONCE").containsMatchIn(t) -> "OD"
            else -> null
        }
    }

    private fun section(sb: StringBuilder, title: String, body: String) {
        if (body.isBlank()) return
        sb.appendLine(title)
        body.trim().split('\n').forEach { sb.appendLine("  ${it.trim()}") }
        sb.appendLine()
    }

    private fun mdSection(sb: StringBuilder, title: String, body: String) {
        if (body.isBlank()) return
        sb.appendLine("## $title")
        sb.appendLine()
        sb.appendLine(body.trim())
        sb.appendLine()
    }

    private fun blank(s: String): String = if (s.isBlank()) "—" else s

    /* ------------------------------- serialization ------------------------------- */

    fun toJson(d: Data): String = J.obj(
        "procedureTitle" to d.procedureTitle,
        "preOpDiagnosis" to d.preOpDiagnosis,
        "postOpDiagnosis" to d.postOpDiagnosis,
        "surgeonName" to d.surgeonName,
        "assistantName" to d.assistantName,
        "anesthetistName" to d.anesthetistName,
        "anesthesiaType" to d.anesthesiaType,
        "incision" to d.incision,
        "operativeFindings" to d.operativeFindings,
        "procedureSteps" to d.procedureSteps,
        "bloodLossMl" to d.bloodLossMl,
        "drains" to d.drains,
        "specimenSent" to d.specimenSent,
        "spongeCountCorrect" to d.spongeCountCorrect,
        "immediatePostOpOrders" to d.immediatePostOpOrders
    ).toJson()

    fun fromJson(json: String): Data? = try {
        val o = J.parse(json) as? J.Obj ?: return null
        Data(
            procedureTitle = o.strOr("procedureTitle", ""),
            preOpDiagnosis = o.strOr("preOpDiagnosis", ""),
            postOpDiagnosis = o.strOr("postOpDiagnosis", ""),
            surgeonName = o.strOr("surgeonName", ""),
            assistantName = o.str("assistantName")?.takeIf { it.isNotBlank() },
            anesthetistName = o.str("anesthetistName")?.takeIf { it.isNotBlank() },
            anesthesiaType = o.strOr("anesthesiaType", "GA"),
            incision = o.strOr("incision", ""),
            operativeFindings = o.strOr("operativeFindings", ""),
            procedureSteps = o.strOr("procedureSteps", ""),
            bloodLossMl = o.int("bloodLossMl"),
            drains = o.str("drains")?.takeIf { it.isNotBlank() },
            specimenSent = o.str("specimenSent")?.takeIf { it.isNotBlank() },
            spongeCountCorrect = o.bool("spongeCountCorrect") ?: true,
            immediatePostOpOrders = o.strs("immediatePostOpOrders")
        )
    } catch (e: Exception) {
        null
    }
}
